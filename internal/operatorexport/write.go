package operatorexport

import (
	"fmt"
	"io"

	"sigs.k8s.io/yaml"
)

const header = `# Kong Operator resources generated by kongctl dump operator.
#
# Each resource adopts an existing Konnect entity through spec.adopt. Once
# adopted, the operator owns the entity: it writes the resource's full spec back
# to Konnect, and deleting the resource deletes the entity in Konnect. The
# KonnectGatewayControlPlane is a read-only mirror and is never modified.
`

// Write serializes manifests as a multi-document YAML stream.
func Write(w io.Writer, manifests []Manifest) error {
	if _, err := io.WriteString(w, header); err != nil {
		return fmt.Errorf("write header: %w", err)
	}
	for _, m := range manifests {
		out, err := yaml.Marshal(m.Object)
		if err != nil {
			return fmt.Errorf("encode %s %s: %w", m.Kind, m.Name, err)
		}
		if _, err := fmt.Fprintf(w, "---\n%s", out); err != nil {
			return fmt.Errorf("write %s %s: %w", m.Kind, m.Name, err)
		}
	}
	return nil
}
